#!/usr/bin/env python3
"""clone_agent - a clone as a tournament bot file (class Agent), for subprocess runs (kit local_sim machinery).

    CLONE_PROFILE=profiles/kojack.json CLONE_SEED=7 python3 -c "import clone_agent; a = clone_agent.Agent()"

class Agent reads the profile path from the environment variable CLONE_PROFILE (and an optional integer
seed from CLONE_SEED; default = a stable hash of the profile slug). If the profile cannot be read it falls
back to profiles/field.json, and if that fails too it plays a built-in default policy (it never raises).

IMPORTANT: the kit's engine/players.py SubprocessPlayer starts every bot with a minimal environment
(PATH, PYTHONDONTWRITEBYTECODE, PYTHONUNBUFFERED, OMP_NUM_THREADS), so CLONE_PROFILE set in the parent
process does NOT reach a bot started by local_sim.py / SubprocessPlayer. For those runs write a wrapper
bot file with the profile path baked in (it subclasses this Agent):

    python3 clone_agent.py --make profiles/kojack.json --out out/bots/kojack.py [--seed 7]
    python3 clone_agent.py --make-all --out out/bots          # one wrapper per profile in profiles/index.json
    python3 ../../imperial-ai-hack-pokerbots-kit/local_sim.py ../v10/bot.py out/bots/kojack.py out/bots/red.py ...
"""
import argparse
import json
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
import clone  # noqa: E402

FIELD = os.path.join(HERE, "profiles", "field.json")


def _load(path):
    try:
        with open(path) as fh:
            return json.load(fh)
    except Exception:
        return None


class Agent:
    PROFILE = None      # wrapper files set these two class attributes
    SEED = None

    def __init__(self):
        path = self.PROFILE or os.environ.get("CLONE_PROFILE") or FIELD
        prof = _load(path) or _load(FIELD) or {"team": "default"}
        seed = self.SEED
        if seed is None:
            try:
                seed = int(os.environ.get("CLONE_SEED", ""))
            except ValueError:
                seed = zlib.crc32(str(prof.get("slug", prof.get("team", ""))).encode()) & 0xFFFF
        self.profile_path = path
        self._a = clone.make_agent(prof, seed)

    def on_table_start(self, info):
        try:
            self._a.on_table_start(info)
        except Exception:
            pass

    def act(self, state):
        return self._a.act(state)          # CloneAgent.act never raises

    def on_hand_end(self, summary):
        try:
            self._a.on_hand_end(summary)
        except Exception:
            pass


_WRAPPER = '''"""Clone of {team!r} (generated by testbench/clone_agent.py). Profile: {profile}"""
import sys
sys.path.insert(0, {here!r})
import clone_agent as _ca  # noqa: E402


class Agent(_ca.Agent):
    PROFILE = {profile!r}
    SEED = {seed!r}
'''


def make_bot_file(profile_path, out_path, seed=None):
    """Write a self-contained wrapper bot file for the profile (works under SubprocessPlayer/local_sim)."""
    profile_path = os.path.abspath(profile_path)
    prof = _load(profile_path)
    if prof is None:
        raise SystemExit("cannot read profile %s" % profile_path)
    d = os.path.dirname(os.path.abspath(out_path))
    os.makedirs(d, exist_ok=True)
    with open(out_path, "w") as fh:
        fh.write(_WRAPPER.format(team=prof.get("team"), profile=profile_path, here=HERE, seed=seed))
    return out_path


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--make", help="profile JSON to wrap")
    ap.add_argument("--make-all", action="store_true", help="wrap every profile in profiles/index.json")
    ap.add_argument("--out", required=True, help="output .py file (--make) or folder (--make-all)")
    ap.add_argument("--seed", type=int, default=None, help="fixed clone seed (default: hash of the slug)")
    a = ap.parse_args()
    if a.make:
        print(make_bot_file(a.make, a.out, a.seed))
    elif a.make_all:
        idx = _load(os.path.join(HERE, "profiles", "index.json")) or {}
        for team, e in sorted(idx.items()):
            out = os.path.join(a.out, e["slug"] + ".py")
            make_bot_file(os.path.join(HERE, "profiles", e["slug"] + ".json"), out, a.seed)
        print("wrote %d wrapper bots to %s" % (len(idx), a.out))
    else:
        ap.error("give --make PROFILE or --make-all")


if __name__ == "__main__":
    main()
