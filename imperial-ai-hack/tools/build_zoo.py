"""Assemble the self-contained zoo bots from tools/zoo_src/.

    python3 tools/build_zoo.py

Every file in tools/zoo_src/ other than _kernel.py is one bot: its docstring and the
ARCHETYPE / TIER / LEAK constants, then a line `#@KERNEL core [mc] [tracker]` naming the
kernel sections it needs, then its `class Agent`. The output, zoo/<name>.py, is a single
standard-library-only file (the kernel sections are pasted in), so each bot can be handed
to the kit's local_sim.py or to any other harness on its own. Edit the sources here and
rebuild; do not edit zoo/*.py by hand. Also rewrites zoo/README.md from the constants.
"""
import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "zoo_src")
OUT = os.path.join(os.path.dirname(HERE), "zoo")
TIER_ORDER = {"fish": 0, "medium": 1, "strong": 2}


def kernel_sections():
    sections = {}
    name = None
    with open(os.path.join(SRC, "_kernel.py")) as fh:
        for line in fh:
            if line.startswith("#@@ "):
                name = line.split()[1]
                sections[name] = []
            elif name:
                sections[name].append(line)
    return {k: "".join(v).rstrip("\n") + "\n" for k, v in sections.items()}


def constants(source):
    """Module docstring and the string constants of a built bot file."""
    tree = ast.parse(source)
    out = {"doc": ast.get_docstring(tree) or ""}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            t = node.targets[0]
            if isinstance(t, ast.Name) and isinstance(node.value, ast.Constant) \
                    and isinstance(node.value.value, str):
                out[t.id] = node.value.value
    return out


def main():
    sections = kernel_sections()
    os.makedirs(OUT, exist_ok=True)
    rows = []
    for fn in sorted(os.listdir(SRC)):
        if not fn.endswith(".py") or fn.startswith("_"):
            continue
        with open(os.path.join(SRC, fn)) as fh:
            body = fh.read()
        marker = [l for l in body.splitlines() if l.startswith("#@KERNEL")]
        if len(marker) != 1:
            sys.exit("%s: expected exactly one #@KERNEL line" % fn)
        head, tail = body.split(marker[0] + "\n", 1)
        parts = [head.rstrip("\n") + "\n",
                 "\n# ---- shared zoo kernel (pasted in by tools/build_zoo.py; edit tools/zoo_src) ----\n"]
        for sec in marker[0].split()[1:]:
            parts.append(sections[sec] + "\n")
        parts.append("\n# ---- the bot ----\n" + tail.lstrip("\n"))
        text = "".join(parts)
        compile(text, fn, "exec")
        with open(os.path.join(OUT, fn), "w") as fh:
            fh.write(text)
        c = constants(text)
        for key in ("ARCHETYPE", "TIER", "LEAK"):
            if key not in c:
                sys.exit("%s: missing %s" % (fn, key))
        if c["TIER"] not in TIER_ORDER:
            sys.exit("%s: TIER must be fish, medium or strong" % fn)
        rows.append((fn, c))

    rows.sort(key=lambda r: (TIER_ORDER[r[1]["TIER"]], r[0]))
    lines = [
        "# Opponent zoo",
        "",
        "Stand-ins for what other teams are likely to upload. Every file is self-contained",
        "(class `Agent`, standard library only, a few microseconds to ~0.3 ms per decision) and",
        "deterministic: its dice are re-seeded every hand from its seat, the hand number and its",
        "own hole cards. Generated by `tools/build_zoo.py` from `tools/zoo_src/`; edit there.",
        "",
        "`tier` is what the gauntlet uses to blend a table: fish = big donators, medium = the",
        "bulk of a student field, strong = reference bots that punish candidates which only",
        "beat fish.",
        "",
        "| file | tier | archetype | what it does | leak to exploit |",
        "|---|---|---|---|---|",
    ]
    for fn, c in rows:
        doc = " ".join(c["doc"].split())
        lines.append("| `%s` | %s | %s | %s | %s |" % (fn, c["TIER"], c["ARCHETYPE"], doc, c["LEAK"]))
    lines += [
        "",
        "The kit's three house bots (`examples/calling_station.py`, `random_bot.py`,",
        "`tight_aggressive.py`) join the pool with `--field mixed` or `--field house`.",
        "",
    ]
    with open(os.path.join(OUT, "README.md"), "w") as fh:
        fh.write("\n".join(lines))
    print("built %d bots into %s" % (len(rows), OUT))


if __name__ == "__main__":
    main()
